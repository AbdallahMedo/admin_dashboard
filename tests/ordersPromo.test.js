import { test } from 'node:test';
import assert from 'node:assert/strict';
globalThis.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
globalThis.document = { addEventListener() {}, getElementById: () => ({}), documentElement: { setAttribute() {} }, body: { classList: { toggle() {} } } };
const { validPercentage, promoStatus, canTogglePromo } = await import('../src/js/views/promoCodesView.js');
const { openOrderDetailDrawer } = await import('../src/js/views/ordersView.js');
const { api } = await import('../src/js/api/client.js');
const { modal } = await import('../src/js/ui/modal.js');
const { toast } = await import('../src/js/ui/toast.js');
test('percentages enforce bounds and two decimal places', () => {
  for (const value of ['0.01', '15', '15.25', '100']) assert.equal(validPercentage(value), true);
  for (const value of ['', '0', '-1', '100.01', '1.001', 'NaN', '1e2']) assert.equal(validPercentage(value), false);
});
test('used and expired codes cannot be enabled or disabled', () => {
  const now = Date.parse('2030-01-01');
  const code = { status: 'Disabled', expiresAt: '2031-01-01', usedAt: null };
  assert.equal(canTogglePromo(code, now), true);
  assert.equal(canTogglePromo({ ...code, status: 'Active' }, now), true);
  assert.equal(canTogglePromo({ ...code, usedAt: '2029-12-31' }, now), false);
  assert.equal(promoStatus({ ...code, usedAt: '2029-12-31' }, now), 'Used');
  assert.equal(canTogglePromo({ ...code, expiresAt: '2029-01-01' }, now), false);
  assert.equal(canTogglePromo({ ...code, expiresAt: 'invalid' }, now), false);
  assert.equal(canTogglePromo({ ...code, status: 'Used' }, now), false);
});
test('order detail uses API fields and rolls back failed item updates', async () => {
  const order = { id: 'o1', address: 'API address', city: 'API city', governorate: 'API governorate', customerNotes: 'API notes', subtotal: 100, discountPercentage: 15, discountAmount: 15, shippingCost: 20, total: 105, items: [{ id: 'i1', status: 'Confirmed' }] };
  let change, html, request;
  const select = { dataset: {}, value: 'Confirmed', getAttribute: () => 'i1', addEventListener: (_, handler) => { change = handler; } };
  const action = { addEventListener() {} };
  modal.showDrawer = options => { html = options.contentHtml; options.onOpen({ querySelector: () => action, querySelectorAll: () => [select] }); };
  let error;
  toast.success = () => {};
  toast.error = message => { error = message; };
  api.request = async (path, options) => { if (!options || options.method === 'GET') return order; request = { path, ...options }; throw new Error('API status rejected'); };
  await openOrderDetailDrawer('o1');
  for (const text of ['API address', 'API city', 'API governorate', 'API notes', 'Subtotal', 'Discount (%)', 'Discount amount', 'Shipping']) assert.ok(html.includes(text), text);
  select.value = 'ReadyForShipping';
  await change();
  assert.equal(request.path, '/api/admin/orders/o1/items/i1/status');
  assert.equal(request.method, 'PATCH');
  assert.deepEqual(request.body, { status: 'ReadyForShipping' });
  assert.equal(select.value, 'Confirmed');
  assert.equal(select.disabled, false);
  assert.equal(error, 'API status rejected');
  api.request = async () => null;
  select.value = 'Processing'; await change();
  assert.equal(select.dataset.savedStatus, 'Processing');
  api.request = async () => { throw new Error('Rejected'); };
  select.value = 'Delivered'; await change();
  assert.equal(select.value, 'Processing');
});
